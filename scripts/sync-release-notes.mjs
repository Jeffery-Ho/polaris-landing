#!/usr/bin/env node
// Sync release notes from the extension repository into the website.
//
//   node scripts/sync-release-notes.mjs [path/to/Polaris-AI-Chat-Navigator]
//
// Reads src/release-notes.js, dates each version by the commit that first added it
// (versions not yet committed get today's date), applies the website naming rule
// (Table of Contents / Outline, never Chapter View or Chapters), and writes
// assets/release-notes.js plus the static, indexable release-notes/index.html.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const extension = resolve(process.argv[2] || join(site, "..", "Polaris-for-Web"));
const sourcePath = join(extension, "src", "release-notes.js");
const source = readFileSync(sourcePath, "utf8");

const start = source.indexOf("Object.freeze([", source.indexOf("RELEASE_NOTES"));
let depth = 0;
let end = -1;
for (let index = source.indexOf("[", start); index < source.length; index += 1) {
  if (source[index] === "[") depth += 1;
  else if (source[index] === "]" && --depth === 0) { end = index + 1; break; }
}
const notes = new Function(`return ${source.slice(start, end)})`)();

const today = new Date().toISOString().slice(0, 10);
function firstDate(version) {
  try {
    const out = execFileSync("git", ["-C", extension, "log", "--reverse", "--format=%cs", "-S", `version: "${version}"`, "--", "src/release-notes.js"], { encoding: "utf8" });
    return out.split("\n").find(Boolean) || today;
  } catch {
    return today;
  }
}

// Feature names on the website: Table of Contents (目录) and Outline (大纲).
const rules = {
  en: [
    [/Navigation and Chapters/g, "Table of Contents and Outline"],
    [/navigation, Chapter View, and settings/g, "Table of Contents, Outline and settings"],
    [/navigation, chapters, and settings/g, "Table of Contents, Outline and settings"],
    [/Chapter View/g, "Outline"],
    [/Chapter view/g, "Outline"],
    [/Chapters/g, "Sections"],
    [/Chapter/g, "Section"],
    [/chapters/g, "sections"],
    [/chapter/g, "section"]
  ],
  zh: [
    [/导航与章节/g, "目录与大纲"],
    [/导航、章节和设置/g, "目录、大纲和设置"],
    [/章节视图/g, "大纲"],
    [/章节/g, "小节"]
  ]
};
const rename = (text, locale) => rules[locale].reduce((value, [pattern, next]) => value.replace(pattern, next), text);
const localize = (entry, locale) => ({
  title: rename(entry.title, locale),
  changes: (entry.changes || (entry.copy ? [entry.copy] : [])).map((change) => rename(change, locale))
});
const semver = (version) => version.split(".").map(Number);
const compare = (a, b) => { const x = semver(a.version), y = semver(b.version); for (let i = 0; i < 3; i += 1) if (x[i] !== y[i]) return y[i] - x[i]; return 0; };

const data = notes.map((note) => ({
  version: note.version,
  date: firstDate(note.version),
  en: localize(note.en, "en"),
  zh: localize(note.zh, "zh")
})).sort(compare);

writeFileSync(join(site, "assets", "release-notes.js"),
  `// Generated by scripts/sync-release-notes.mjs from the extension's src/release-notes.js. Do not edit by hand.\nexport const RELEASE_NOTES = Object.freeze(${JSON.stringify(data, null, 2)});\n`);

const escape = (value) => value.replace(/[&<>"]/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[character]);
const anchor = (version) => `v${version.replaceAll(".", "-")}`;
const monthName = (date, locale) => {
  const [year, month] = date.split("-").map(Number);
  return locale === "zh" ? `${year} 年 ${month} 月` : new Date(Date.UTC(year, month - 1, 1)).toLocaleString("en-US", { month: "long", year: "numeric", timeZone: "UTC" });
};
const dayLabel = (date, locale) => {
  const [year, month, day] = date.split("-").map(Number);
  return locale === "zh" ? `${month} 月 ${day} 日` : new Date(Date.UTC(year, month - 1, day)).toLocaleString("en-US", { month: "short", day: "numeric", timeZone: "UTC" });
};
const months = [...new Set(data.map((note) => note.date.slice(0, 7)))];

function article(locale) {
  const lang = locale === "zh" ? "zh-CN" : "en";
  const heading = locale === "zh" ? "版本说明" : "Release notes";
  const intro = locale === "zh"
    ? `Polaris 的全部更新，按月份整理，最新的在最前。共 ${data.length} 个版本。`
    : `Every Polaris update, grouped by month, newest first. ${data.length} versions so far.`;
  const jump = months.map((month) => `<a href="#${locale}-${month}">${escape(monthName(`${month}-01`, locale))}</a>`).join("");
  const sections = months.map((month) => {
    const entries = data.filter((note) => note.date.startsWith(month)).map((note) => {
      const text = note[locale];
      const changes = text.changes.map((change) => `<li>${escape(change)}</li>`).join("");
      return `      <article class="rn-entry" id="${locale === "en" ? anchor(note.version) : `zh-${anchor(note.version)}`}">
        <p class="rn-meta"><span class="rn-version">v${note.version}</span><time datetime="${note.date}">${dayLabel(note.date, locale)}</time></p>
        <h3>${escape(text.title)}</h3>
        <ul>${changes}</ul>
      </article>`;
    }).join("\n");
    return `    <section class="rn-month" id="${locale}-${month}" aria-labelledby="${locale}-${month}-title">
      <h2 id="${locale}-${month}-title">${escape(monthName(`${month}-01`, locale))}</h2>
${entries}
    </section>`;
  }).join("\n");
  return `  <article lang="${lang}" data-legal-locale="${lang}">
    <h1>${heading}</h1>
    <p class="rn-intro">${escape(intro)}</p>
    <nav class="rn-months" aria-label="${locale === "zh" ? "按月份跳转" : "Jump to month"}">${jump}</nav>
${sections}
  </article>`;
}

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Every Polaris AI release, grouped by month: new platforms, Table of Contents and Outline improvements, long-conversation reading and fixes.">
  <link rel="canonical" href="https://polaris-ai.work/release-notes/">
  <link rel="icon" type="image/png" sizes="32x32" href="../icons/polaris-icon-32.png?v=73794ca8">
  <link rel="stylesheet" href="../assets/theme.css?v=15e667bb">
  <link rel="stylesheet" href="../assets/legal.css?v=71f42098">
  <link rel="stylesheet" href="../assets/release-notes.css">
  <script src="../assets/legal.js" defer></script>
  <title>Release notes · Polaris AI</title>
</head>
<body>
<main>
  <nav aria-label="Polaris">
    <a href="../">Polaris AI</a>
    <div class="language" role="group" aria-label="Language / 语言">
      <button type="button" data-legal-language="en" lang="en">English</button>
      <button type="button" data-legal-language="zh-CN" lang="zh-CN">简体中文</button>
    </div>
  </nav>
${article("en")}
${article("zh")}
  <footer>
    <span lang="en" data-legal-locale="en"><a href="../">Home</a> · <a href="../#install">Install</a> · <a href="../privacy.html">Privacy Policy</a></span>
    <span lang="zh-CN" data-legal-locale="zh-CN"><a href="../">首页</a> · <a href="../#install">安装</a> · <a href="../privacy.html">隐私政策</a></span>
  </footer>
</main>
</body>
</html>
`;
mkdirSync(join(site, "release-notes"), { recursive: true });
writeFileSync(join(site, "release-notes", "index.html"), html);
console.log(`Synced ${data.length} release notes (${data[0].version} on ${data[0].date} … ${data.at(-1).version}).`);
